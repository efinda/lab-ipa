function makeAlat(
  id: string,
  kode: string,
  nama: string,
  kategoriId: string,
  labId: string,
  merk: string,
  total: number,
  dipinjam: number,
  kondisi: Alat['kondisi'],
  lokasi: string,
  tahun: number,
  harga: number
): Alat {
  const foto =
    labId === 'lab-fisika' ? FOTO_FISIKA : labId === 'lab-kimia' ? FOTO_KIMIA : FOTO_BIOLOGI;
  return {
    id,
    kode_inventaris: kode,
    nama_alat: nama,
    kategori_id: kategoriId,
    lab_id: labId,
    merk,
    jumlah_total: total,
    jumlah_tersedia: Math.max(0, total - dipinjam),
    jumlah_dipinjam: dipinjam,
    kondisi,
    lokasi_penyimpanan: lokasi,
    foto_url: foto,
    qr_code: `SIMLAB:${kode}:${nama}`,
    tahun_pengadaan: tahun,
    harga,
    created_at: `${tahun}-08-10T08:00:00.000Z`,
  };
}

